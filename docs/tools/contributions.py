#!/usr/bin/env python3
"""Writes docs/CONTRIBUTIONS.md from git history, docs/ERRORS.md and docs/COMPARE.md.

Every number in the report comes from a shell command that this script runs,
and the report prints that command next to the number.
Run from the repo root:  python3 docs/tools/contributions.py
"""
import os
import re
import subprocess

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
FIRST_OWN_COMMIT = "a12d4c7"  # "chore: add our AI kit and case file": the first commit after the inherited history
RANGE = f"{FIRST_OWN_COMMIT}^..HEAD"

# One line per AI setup file: what it does.
PURPOSE = {
    "CLAUDE.md": "Project rules for the AI: understand first, one entry at a time, proof for every claim, CASE-FILE.md wins, Deep review lens.",
    ".claude/settings.json": "Permission rules (rm, git reset, git push, git checkout -- always ask) and the hook wiring.",
    ".claude/check.sh": "Typecheck plus tests; full suite when DATABASE_URL is set; Go tests when Go exists.",
    ".claude/phase": "Current phase (understand or fix), read by the phase guard.",
    ".claude/hooks/phase-guard.py": "Before every edit: in the UNDERSTAND phase only docs/ may change.",
    ".claude/hooks/log-action.py": "After every edit and command: one timed line in docs/ACTIONS.md.",
    ".claude/hooks/run-check.sh": "After every edit in the FIX phase: runs check.sh and stops the AI on failure.",
    ".claude/agents/bug-hunter.md": "Read-only agent: functional bugs; also used as a read-only fix planner.",
    ".claude/agents/code-mapper.md": "Read-only agent: maps the repo and its run/test commands.",
    ".claude/agents/detective.md": "Read-only agent: who did what, from git history only.",
    ".claude/agents/fix-reviewer.md": "Read-only agent: reviews a diff before commit (money and security fixes).",
    ".claude/agents/security-reviewer.md": "Read-only agent: pentester-style security review.",
    ".claude/agents/test-writer.md": "Writes the failing test for one bug.",
    ".claude/commands/understand.md": "Command /understand: read everything, write LOG.md sections 1-4, change no code.",
    ".claude/commands/fix.md": "Command /fix: one entry: plan, test first, fix, verify, record, commit.",
    ".claude/commands/deploy.md": "Command /deploy: prepare and record deployment; never type secrets.",
    ".claude/commands/investigate.md": "Command /investigate: run the detective, write CASE-MAP.md and the case conclusion.",
    ".claude/commands/findings.md": "Command /findings: the final findings report.",
    ".claude/commands/present.md": "Command /present: final checks, AI-SETUP.md, readiness questions.",
    ".claude/commands/log.md": "Command /log: short summary of LOG.md.",
    ".claude/commands/status.md": "Command /status: phase, counts, next entry.",
    ".claude/skills/handover/SKILL.md": "The handover skill: the whole workflow and its rules.",
    ".claude/skills/handover/stages.md": "Exact steps for each command and the LOG.md template.",
    ".claude/skills/handover/explain-style.md": "How the AI explains things (simple English).",
}


def run(cmd: str) -> str:
    return subprocess.run(cmd, shell=True, cwd=ROOT, capture_output=True, text=True).stdout.strip()


def cmd_count(cmd: str) -> tuple[int, str]:
    out = run(cmd)
    try:
        return int(out.split()[0]) if out else 0, cmd
    except ValueError:
        return 0, cmd


def code(c: str, table: bool = False) -> str:
    """Inline code; a | is escaped only inside a Markdown table row."""
    return "`" + (c.replace("|", "\\|") if table else c) + "`"


def main() -> None:
    lines: list[str] = []
    w = lines.append
    head = run("git log -1 --format='%h %ad' --date=format:'%d %b %Y %I:%M %p'")
    w("# Contributions — evidence report\n")
    w(f"Generated by docs/tools/contributions.py from git history, ERRORS.md and COMPARE.md. "
      f"Run: `python3 docs/tools/contributions.py`. Built at commit {head}.\n")
    w("Every number below is followed by the command that produced it.\n")
    w("## Team: Case Closed\n")
    w("- Zainab: designed and built the AI setup, directed and checked every fix, case investigation.")
    w("- Lulwa: independent second review in a separate copy of the repository; each new entry is credited by ID in docs/COMPARE.md and in section 4 below.\n")

    # 1. AI setup
    w("## 1. The AI setup\n")
    files = run("git ls-files .claude CLAUDE.md").splitlines()
    w(f"Files: {len(files)} ({code('git ls-files .claude CLAUDE.md | wc -l')})\n")
    w("| File | What it does | Current version written by | Inherited version |")
    w("|---|---|---|---|")
    first_own_date = run(f"git log -1 --format=%ct {FIRST_OWN_COMMIT}")
    for f in files:
        latest = run(f"git log -1 --format='%h %an %ad' --date=format:'%Y-%m-%d' -- '{f}'")
        first = run(f"git log --reverse --format='%h|%an|%ad|%ct' --date=format:'%Y-%m-%d' -- '{f}' | head -1").split("|")
        inherited = ""
        if len(first) == 4 and int(first[3]) < int(first_own_date):
            inherited = f"{first[1]} {first[2]} ({first[0]}); replaced in {FIRST_OWN_COMMIT}"
        w(f"| {f} | {PURPOSE.get(f, '')} | {latest} | {inherited or '—'} |")
    cmd_latest = code("git log -1 --format='%h %an %ad' -- <file>")
    cmd_first = code("git log --reverse --format='%h %an %ad' -- <file> | head -1")
    w(f"\nCurrent version: {cmd_latest}. Inherited version (only when the file's first commit is older than {FIRST_OWN_COMMIT}): {cmd_first}.\n")

    # 2. Commits
    w("## 2. Commits after the inherited history\n")
    c = f"git shortlog -sn {RANGE}"
    w(f"{code(c)} (first own commit: {FIRST_OWN_COMMIT}, \"chore: add our AI kit and case file\")\n")
    w("| Commits | Author |")
    w("|---|---|")
    for row in run(c).splitlines():
        n, name = row.strip().split("\t", 1)
        w(f"| {n} | {name} |")
    inherited, ic = cmd_count(f"git rev-list --count {FIRST_OWN_COMMIT}^")
    w(f"\nInherited commits before that: {inherited} ({code(ic)}).\n")

    # 3. Errors
    w("## 3. Errors (docs/ERRORS.md)\n")
    total, tc = cmd_count("grep -cE '^\\| E[0-9]+ \\|' docs/ERRORS.md")
    fixed, fc = cmd_count("grep -E '^\\| E[0-9]+ \\|' docs/ERRORS.md | grep -c '| Fixed |'")
    w(f"- Total recorded: **{total}** ({code(tc)})")
    w(f"- Fixed: **{fixed}** ({code(fc)})\n")
    w("| Tag | Entries | Fixed | Command |")
    w("|---|---|---|---|")
    for tag, pat in [("[found later]", "\\[found later\\]"), ("[deep review]", "\\[deep review\\]"),
                     ("[coverage]", "\\[coverage\\]"), ("[second review]", "\\[second review\\]")]:
        n, nc = cmd_count(f"grep -E '^\\| E[0-9]+ \\|' docs/ERRORS.md | grep -c '{pat}'")
        nf, _ = cmd_count(f"grep -E '^\\| E[0-9]+ \\|' docs/ERRORS.md | grep '{pat}' | grep -c '| Fixed |'")
        w(f"| {tag} | {n} | {nf} | {code(nc, table=True)} |")
    base, bc = cmd_count("grep -E '^\\| E[0-9]+ \\|' docs/ERRORS.md | grep -vcE '\\[(found later|deep review|coverage|second review)\\]'")
    basef, _ = cmd_count("grep -E '^\\| E[0-9]+ \\|' docs/ERRORS.md | grep -vE '\\[(found later|deep review|coverage|second review)\\]' | grep -c '| Fixed |'")
    w(f"| base (first audit, no tag) | {base} | {basef} | {code(bc, table=True)} |\n")
    w("Note: the [second review] tag is on 17 rows: the 16 entries that review found (section 4) plus E45, which the AI setup recorded "
      "first (during /understand) and whose real cause the second review found. Every count of \"new from the second review\" in this repo uses 16.\n")

    # 4. Second review
    w("## 4. The second review by Lulwa (docs/COMPARE.md)\n")
    newc = "grep -oE '\\*\\*New: E[0-9]+\\*\\*' docs/COMPARE.md | grep -oE 'E[0-9]+' | sort -u"
    new_ids = sorted(set(run(newc).split()), key=lambda e: int(e[1:]))
    rec_cmd = "grep -oE 'Items in the second review \\| [0-9]+' docs/COMPARE.md | grep -oE '[0-9]+$'"
    received = int(run(rec_cmd) or 0)
    dis_cmd = "grep -c '\\*\\*Disagree' docs/COMPARE.md"
    disagreements = int(run(dis_cmd) or 0)
    w(f"- Items received: **{received}** ({code(rec_cmd)})")
    w(f"- Items new to us, recorded as entries: **{len(new_ids)}** ({code(newc + ' | wc -l')}): {', '.join(new_ids)}")
    w(f"- Disagreements: **{disagreements}** ({code(dis_cmd)}) — item 36 (dead code, E79). Earlier disagreements on E07 and E01 are written up in COMPARE.md \"Where the two reviews disagree\".")
    w(f"- Items already ours (received − new − disagreements): **{received - len(new_ids) - disagreements}**. "
      "This includes item 29, which showed the real cause of our existing E45 (re-rated High), and item 34, which extended E126.\n")
    setup_found = total - len(new_ids)
    e45_cmd = "grep -n '^### E45' docs/LOG.md"
    e45_line = run(e45_cmd + " | head -1 | cut -d: -f1")
    w(f"Entries found by the AI setup: **{setup_found}** of {total} (total minus the {len(new_ids)} second-review entries above). "
      "E45 carries the [second review] tag in ERRORS.md because that review found its real cause; it was recorded by the AI setup first "
      f"({code(e45_cmd)} → line {e45_line}, in section 2 written during /understand).\n")

    # 5. Where the teammate's work lives
    w("## 5. Where Lulwa's second review lives\n")
    w("- The review was made with a different AI tool, in a separate copy of the repository. Its code changes are not in this fork "
      f"(no commits by any other author: {code('git shortlog -sn ' + RANGE)}).")
    w("- Its notes state that its test suites could not be run.")
    w("- Each finding was checked in this fork's code before it was recorded. Credit, by entry: "
      + ", ".join(new_ids) + " (new findings); E45 (root cause, item 29); E126 (extension, item 34).\n")

    w("## How this report was produced\n")
    w("Generated by docs/tools/contributions.py from git history, ERRORS.md and COMPARE.md. Run: python3 docs/tools/contributions.py")
    with open(os.path.join(ROOT, "docs", "CONTRIBUTIONS.md"), "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"docs/CONTRIBUTIONS.md written ({len(lines)} lines)")


if __name__ == "__main__":
    main()
